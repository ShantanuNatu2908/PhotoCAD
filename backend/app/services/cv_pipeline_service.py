"""
PhotoCAD - Cloud GPU CV & 3D Fusion Orchestration Bridge (Phase 3)
Document ID: PCAD-SAD-002 / PCAD-API-ADT-003 (FR-07..FR-10, NFR-02)

Coordinates the transition from 6 calibrated PNG keyframes to a unified, metric-scaled
3D point cloud (.PLY) + structured Open3DGeometryReport ADT:
  - Production / Cloud Mode: Dispatches to Modal serverless NVIDIA L4 (`photocad-gpu`)
    running SAM 2.1 (BF16) -> Depth Anything (BF16) -> Open3D RANSAC/ICP Fusion.
  - Zero-Heat Offline Dev Fallback: Runs deterministic CPU foreground masking +
    multi-view 3D silhouette/depth projection (with zero PyTorch/CUDA and zero Canny-to-CAD)
    producing real .PLY point clouds and validated Open3DGeometryReport payloads for tests/dev.
"""

